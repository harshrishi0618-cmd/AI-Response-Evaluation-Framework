"""
Data models used throughout the AI Response Evaluation Framework.
"""

from dataclasses import dataclass, field


@dataclass(slots=True)
class EvaluationResult:
    """
    Represents the output of a single evaluation metric.

    Attributes
    ----------
    metric : str
        Name of the evaluation metric.
    score : float
        Score assigned by the evaluator.
    max_score : float
        Maximum possible score.
    confidence : float
        Confidence of the evaluator between 0.0 and 1.0.
    feedback : list[str]
        Suggestions or observations generated by the evaluator.
    """

    metric: str
    score: float
    max_score: float = 10.0
    confidence: float = 1.0
    feedback: list[str] = field(default_factory=list)

    @property
    def percentage(self) -> float:
        """
        Return the score as a percentage.
        """
        return (self.score / self.max_score) * 100

    @property
    def passed(self) -> bool:
        """
        Return whether the evaluation passed.

        A score of 70% or higher is considered a pass.
        """
        return self.percentage >= 70
